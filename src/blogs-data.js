function initBlogsPage() {
  const grid = document.getElementById("blogsGrid");
  const countText = document.getElementById("blogsCount");

  if (!grid || !countText) return;

  const categoryFromPath = getBlogCategoryFromPath();

  // পুরোনো ?category= URL থাকলেও একবার support করবে
  const legacyParams = new URLSearchParams(window.location.search);
  const legacyCategory = legacyParams.get("category");

  const validLegacyCategory = getOnlyBlogCategories().includes(legacyCategory)
    ? legacyCategory
    : "";

  const initialCategory =
    categoryFromPath || validLegacyCategory || BLOGS_ALL_CATEGORY;

  activeBlogCategory = initialCategory;

  // পুরোনো query URL-কে clean slash URL-এ convert করবে
  window.history.replaceState({}, "", getBlogCategoryUrl(activeBlogCategory));

  renderBlogCategories();
  renderMobileBlogCategorySelect();
  renderBlogsGrid();
  initBlogCategorySliderButtons();
}

function waitForBlogsPage() {
  if (document.getElementById("blogsGrid")) {
    initBlogsPage();
    return;
  }

  const observer = new MutationObserver(() => {
    if (document.getElementById("blogsGrid")) {
      observer.disconnect();
      initBlogsPage();
    }
  });

  observer.observe(document.body, {
    childList: true,
    subtree: true,
  });
}

function isBlogCategoryRoute() {
  const parts = window.location.pathname.split("/").filter(Boolean);
  const blogsIndex = parts.indexOf("blogs");

  if (blogsIndex === -1) return false;

  return parts[blogsIndex + 1] === "category" && Boolean(parts[blogsIndex + 2]);
}

async function mountBlogsListingForCategoryRoute(root) {
  const main = root.closest("main");

  if (!main) return false;

  try {
    const response = await fetch("/pages/blogs.html");

    if (!response.ok) {
      throw new Error("Could not load blogs listing page.");
    }

    main.innerHTML = await response.text();

    return true;
  } catch (error) {
    console.error(error);

    window.location.replace("/blogs.html");
    return false;
  }
}
