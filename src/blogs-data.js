function initBlogShare() {
  const copyButton = document.querySelector("[data-blog-copy-link]");

  const message = document.querySelector("[data-blog-copy-message]");

  if (!copyButton) return;

  copyButton.addEventListener("click", async () => {
    try {
      await navigator.clipboard.writeText(window.location.href);

      message?.classList.remove("hidden");

      setTimeout(() => {
        message?.classList.add("hidden");
      }, 1800);
    } catch (error) {
      console.warn("Could not copy blog link:", error);
    }
  });
}

function initBlogTocObserver() {
  const links = Array.from(document.querySelectorAll("[data-blog-toc-link]"));

  if (!links.length) return;

  const sections = links
    .map((link) => {
      const id = link.dataset.blogTocLink;

      return document.getElementById(id);
    })
    .filter(Boolean);

  if (!sections.length) return;

  function setActiveToc(id) {
    links.forEach((link) => {
      const active = link.dataset.blogTocLink === id;

      const dot = link.querySelector("[data-blog-toc-dot]");

      const text = link.querySelector("[data-blog-toc-text]");

      if (dot) {
        dot.classList.toggle("bg-[#0877f9]", active);

        dot.classList.toggle("bg-[#d9e1ec]", !active);
      }

      if (text) {
        text.classList.toggle("text-[#0877f9]", active);

        text.classList.toggle("font-medium", active);

        text.classList.toggle("text-[#61728a]", !active);

        text.classList.toggle("font-normal", !active);
      }
    });
  }

  const observer = new IntersectionObserver(
    (entries) => {
      const visible = entries
        .filter((entry) => entry.isIntersecting)
        .sort((a, b) => b.intersectionRatio - a.intersectionRatio);

      if (!visible.length) return;

      setActiveToc(visible[0].target.id);
    },
    {
      rootMargin: "-100px 0px -55% 0px",

      threshold: [0, 0.2, 0.5, 0.8],
    },
  );

  sections.forEach((section) => {
    observer.observe(section);
  });

  setActiveToc(sections[0].id);
}

